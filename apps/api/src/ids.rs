use uuid::Uuid;

/// Keyed by table name in the `pipewhere` schema. A table's migration checks
/// its id with `pipewhere.is_typeid(id, '<prefix>')`.
pub const PREFIXES: &[(&str, &str)] = &[
    ("channel", "chn"),
    ("content", "cnt"),
    ("publication", "pub"),
    ("publication_attempt", "att"),
];

const CROCKFORD: &[u8; 32] = b"0123456789abcdefghjkmnpqrstvwxyz";

pub fn new_id(table: &str) -> String {
    let Some((_, prefix)) = PREFIXES.iter().find(|(name, _)| *name == table) else {
        panic!(
            "No id prefix is listed for table {table:?}. Add one to PREFIXES in apps/api/src/ids.rs."
        );
    };
    format!("{prefix}_{}", suffix(Uuid::now_v7()))
}

// 26 base32 characters hold 130 bits, so the first character carries only the
// UUID's top 3 bits.
fn suffix(uuid: Uuid) -> String {
    let bits = uuid.as_u128();
    (0..26)
        .map(|i| CROCKFORD[(bits >> (125 - 5 * i)) as usize & 31] as char)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    // Generated by typeid-js 1.2.0, the library Auth's generator uses.
    #[test]
    fn suffixes_match_typeid_js() {
        for (uuid, expected) in [
            (
                "00000000-0000-0000-0000-000000000000",
                "00000000000000000000000000",
            ),
            (
                "ffffffff-ffff-ffff-ffff-ffffffffffff",
                "7zzzzzzzzzzzzzzzzzzzzzzzzz",
            ),
            (
                "01890a5d-ac96-774b-bcce-b302099a8057",
                "01h455vb4pex5vsknk084sn02q",
            ),
        ] {
            assert_eq!(suffix(uuid.parse().unwrap()), expected);
        }
    }

    #[test]
    fn every_listed_table_gets_its_own_prefix() {
        for (table, prefix) in PREFIXES {
            let id = new_id(table);
            assert!(id.starts_with(&format!("{prefix}_")), "{id}");
            assert!(id.len() <= 32, "{id}");
        }
    }

    #[test]
    #[should_panic(expected = "No id prefix is listed for table \"team\"")]
    fn a_table_with_no_listed_prefix_fails_loudly() {
        new_id("team");
    }

    #[test]
    fn ids_sort_by_creation_time() {
        let first = new_id("channel");
        std::thread::sleep(std::time::Duration::from_millis(2));
        let second = new_id("channel");
        assert!(first < second, "{first} < {second}");
    }
}
